  function normalize(value) {
    return String(value == null ? '' : value)
      .toLowerCase()
      .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
      .replace(/[إأآٱ]/g, 'ا')
      .replace(/ى/g, 'ي')
      .replace(/ة/g, 'ه')
      .replace(/[—–\-_/|،,.:؛()]+/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  const NAME_INDEX = PRODUCTS
