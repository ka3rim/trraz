  /** Sort any list by a TERAZ sort key. `idOf(item)` must return the TERAZ id; unknown items go last, stable. */
  function ordered(items, key, idOf) {
    const idFn = typeof idOf === 'function' ? idOf : (x) => x.id;
    return items
      .map((item, i) => ({ item, i, r: rank(idFn(item), key) }))
      .sort((a, b) => (a.r - b.r) || (a.i - b.i))
      .map((x) => x.item);
  }

