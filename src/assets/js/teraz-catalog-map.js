  /** Find a TERAZ id from a free-form Salla product name; exact match first, then "contains". */
  function matchByName(name) {
    const n = normalize(name);
    if (!n) return null;
    const exact = NAME_INDEX.find((x) => x.key === n);
    if (exact) return exact.id;
    const partial = NAME_INDEX.find((x) => n.includes(x.key));
    return partial ? partial.id : null;
  }

